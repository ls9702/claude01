/**
 * 드롭 자석 — 끌어다 놓는 배치는 :00 / :30에 달라붙는다 (M45).
 *
 * 사용자 요청 그대로다: 「일정에 아이템 올려놓을때 기본적으로 0분과 30분에
 * 자석처럼 달라붙게」. 손가락으로 놓은 자리는 언제나 「10시 7분」쯤이고, 그
 * 7분은 계획의 사실이 아니라 손의 떨림이다 — 그리고 그 떨림이 남으면 사용자는
 * 상세 시트를 열어 스테퍼를 두 번 눌러 지워야 한다.
 *
 * ## 어디에 걸리고, 어디에 안 걸리나
 *
 * 이 자석은 **드래그 드롭에만** 걸린다:
 *
 * | 길 | 단위 |
 * |---|---|
 * | 그리드에 끌어다 놓기 (배치·이동) | **30분** — 이 파일 |
 * | 배치 시트(`ScheduleSheet`)의 ± 스테퍼 | 15분 (`SNAP_MIN`) |
 * | 엔트리 상세의 ± 스테퍼 | 15분 (`SNAP_MIN`) |
 * | 길이 조절 손잡이 | 15분 (`SNAP_MIN`) |
 *
 * 이유는 하나다: 스테퍼를 누르는 손가락은 **정확하다**. 「10시 15분에 시작」이라고
 * 정한 사람에게서 그 15분을 빼앗을 이유가 없고, 그 길에는 애초에 떨림이 없다.
 * 자석은 부정확한 입력을 다듬는 물건이지 계획의 해상도를 낮추는 물건이 아니다.
 *
 * ## 05시 창과의 관계
 *
 * 받는 값은 **창 오프셋**(05:00 = 0)이지 벽시계가 아니다. 창의 시작이 05:00이라
 * 30분 격자 위에 정확히 놓여 있으므로, 오프셋을 30으로 반올림한 것과 시계를 30으로
 * 반올림한 것은 **같은 분**이다 — 자정을 넘어 다음 날로 넘어가는 드롭(M16-B의
 * 새벽 구간)에서도 그렇다. 그래서 이 함수는 `dropTarget` **앞에서** 한 번만 돌면
 * 되고, 05시 경계 산술은 지금까지처럼 `dayWindow.ts` 한 곳에만 산다.
 *
 * 30의 배수는 15의 배수이기도 하므로, 스토어가 뒤에서 다시 거는
 * `snapMin(…, 15)`은 이 값을 한 톨도 움직이지 않는다.
 */

import { snapMin } from '../utils/time';

/** 드롭 자석의 격자 — :00과 :30. */
export const DROP_SNAP_MIN = 30;

/**
 * 창 오프셋 하나를 가장 가까운 :00 / :30으로.
 *
 * - 정확히 가운데(15분)는 **위로** 붙는다 — `Math.round`의 규칙 그대로고,
 *   `snapMin`이 앱 전체에서 쓰는 그 규칙이다.
 * - 창 위쪽(음수)으로는 넘어가지 않는다: 창의 첫 픽셀보다 이른 분은 이 격자가
 *   만들어 낼 수 있는 값이 아니다. `dropTarget`도 같은 자리를 0으로 자른다.
 * - `NaN`·`Infinity`는 0이다 — 좌표를 못 읽은 드롭이 시간을 발명하지 않는다.
 */
export function snapDropMin(offsetMin: number): number {
  if (!Number.isFinite(offsetMin)) return 0;
  return Math.max(0, snapMin(offsetMin, DROP_SNAP_MIN));
}
